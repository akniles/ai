const status = document.querySelector('#status');
const notice = document.querySelector('#notice');
const events = document.querySelector('#events');
const replay = document.querySelector('#replay');

let active;
let rendered;
let replayVersion = 0;
let preview;

function render(turn) {
  const card = document.createElement('li');
  const label = document.createElement('p');
  const heading = document.createElement('h3');
  const action = document.createElement('p');
  const outcome = document.createElement('p');
  label.className = 'turn';
  label.textContent = 'Turn ' + String(turn.turn).padStart(2, '0');
  heading.textContent = turn.goal;
  action.className = 'action';
  action.textContent = turn.action;
  outcome.textContent = turn.outcome;
  card.append(label, heading, action, outcome);
  events.append(card);
}

function show(data) {
  const key = JSON.stringify(data);
  if (key === rendered) return;
  active = data;
  rendered = key;
  replayVersion++;
  replay.disabled = false;
  replay.hidden = data.mode !== 'preview';
  status.textContent = (data.mode === 'live' ? 'Agent run' : 'Preview') + ' · ' + data.status;
  notice.textContent = data.mode === 'preview'
    ? 'Illustrative replay. These events were not generated by a model.'
    : 'Published reports from the Pi worker.';
  events.replaceChildren();
  data.events.forEach(render);
}

async function getFeed(file, mode) {
  try {
    const res = await fetch(file, { cache: 'no-store', signal: AbortSignal.timeout(4000) });
    if (!res.ok) return null;
    const data = await res.json();
    if (data?.mode !== mode || typeof data.status !== 'string' || !Array.isArray(data.events)) return null;
    if (!data.events.every(event => event && Number.isInteger(event.turn)
      && ['goal', 'action', 'outcome'].every(key => typeof event[key] === 'string'))) return null;
    return data;
  } catch {
    return null;
  }
}

replay.addEventListener('click', async () => {
  if (active?.mode !== 'preview') return;
  const version = ++replayVersion;
  replay.disabled = true;
  events.replaceChildren();
  for (const [index, turn] of active.events.entries()) {
    if (index) await new Promise(resolve => setTimeout(resolve, 650));
    if (version !== replayVersion) return;
    render(turn);
  }
  replay.disabled = false;
});

async function refresh() {
  const live = await getFeed('./run.json', 'live');
  if (live || preview) show(live || preview);
  else {
    status.textContent = 'Offline';
    notice.textContent = 'The experiment feed is unavailable. Try refreshing.';
  }
  setTimeout(refresh, 4000);
}

getFeed('./preview.json', 'preview').then(data => {
  preview = data;
  if (preview) show(preview);
  refresh();
});
